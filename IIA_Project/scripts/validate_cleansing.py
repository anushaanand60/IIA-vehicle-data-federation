"""Measure whether cleansing works: labelled noise injection over clean camera captures (rubric 2).

    python scripts/validate_cleansing.py                  # live wrappers (read-only), n=300
    python scripts/validate_cleansing.py --local-db       # this laptop's SQLite copies, no wrapper needed
    python scripts/validate_cleansing.py --n 120 --seed 7

Writes data/cleansing_validation.json (the GUI reads it) and docs/CLEANSING_VALIDATION.md.
Nothing is written to any source: the noisy records exist only in memory.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from mediator import cleansing_validation as cv  # noqa: E402

DOC = ROOT / "docs" / "CLEANSING_VALIDATION.md"


def _cell(v: Any) -> str:
    return "-" if v is None else str(v)


def markdown(rep: Dict[str, Any]) -> str:
    o = rep["overall"]
    lines = [
        "# Cleansing validation (rubric 2)",
        "",
        f"Generated by `python scripts/validate_cleansing.py{' --local-db' if 'SQLite' in rep['source'] else ''}` "
        f"(seed {rep['seed']}, n={rep['n_requested']}, source: {rep['source']}, {rep['generated_at']}). "
        "Deterministic for a given seed and source data.",
        "",
        "**Method.** Clean camera captures (registered read; make, model and colour present and agreeing with the "
        "registration; parseable timestamp; confidence above the floor; no duplicate, no impossible travel) are "
        "sampled with a fixed seed. Each gets one labelled noise type, or none (control). `cleansing.propose` "
        "(detection + the RDR tree + the plate matcher) runs on the noisy set in memory, against a Context built "
        "from the same snapshot of REG and CAM. Nothing is written to any source. Plate misreads draw their OCR "
        "confusions from `data/confusion_costs.json` with the benchmark's own frequencies.",
        "",
        "## Overall",
        "",
        "| measure | value |",
        "|---|---|",
        f"| records scored | {o['records']} ({o['noisy']} noisy, {o['controls']} controls; clean pool {o['clean_pool']}) |",
        f"| detection recall (noisy records with their expected anomaly) | {_cell(o['detection_recall'])} |",
        f"| detection precision (vs false alarms on controls) | {_cell(o['detection_precision'])} |",
        f"| control false-alarm rate | {_cell(o['control_false_alarm_rate'])} |",
        f"| correction accuracy (expected action, and value == original clean value) | {_cell(o['correction_accuracy'])} |",
        f"| wrong corrections (a value set that is not the original) | {o['wrong_corrections']} |",
        f"| **wrong plate corrections** (must be 0) | **{o['plate_wrong_corrections']}** |",
        "",
        "## Per noise type",
        "",
        "| type | n | expected | detection recall | false alarms | correction accuracy | quarantine | flag | wrong | wrong plates |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for kind, t in rep["per_type"].items():
        lines.append(f"| {kind} | {t['n']} | {t['expected']} | {_cell(t['detection_recall'])} | "
                     f"{_cell(t['false_alarm_rate'])} | {_cell(t['correction_accuracy'])} | "
                     f"{_cell(t['quarantine_rate'])} | {_cell(t['flag_rate'])} | {t['wrong_corrections']} | "
                     f"{t['plate_wrong_corrections']} |")
    lines += ["", "## Examples", "", "| type | field | original | noisy | detected | proposed | rules fired | correct |",
              "|---|---|---|---|---|---|---|---|"]
    for e in rep["examples"]:
        lines.append(f"| {e['type']} | {e['field']} | `{e['original']}` | `{e['noisy']}` | "
                     f"{', '.join(e['detected']) or '-'} | {e['proposed']} | {' > '.join(e['rule_path']) or '-'} | "
                     f"{'yes' if e['correct'] else 'no'} |")
    if rep.get("wrong_corrections_detail"):
        lines += ["", "## Every wrong correction (findings)", "",
                  "| type | field | original | noisy | set to | rule | registered make/model/colour of the set value | camera saw |",
                  "|---|---|---|---|---|---|---|---|"]
        for w in rep["wrong_corrections_detail"]:
            prof = w.get("registered_profile_of_set_value") or {}
            lines.append(f"| {w['type']} | {w['field']} | `{w['original']}` | `{w['noisy']}` | `{w['set_to']}` | {w['rule']} | "
                         f"{' / '.join(_cell(prof.get(k)) for k in ('vehicle_make', 'vehicle_model', 'vehicle_colour'))} | "
                         f"{' / '.join(_cell(v) for v in w['observed'].values())} |")
        lines += ["", "Each row is the matcher ACCEPTing a plate one cheap OCR confusion away from a double misread. "
                  "The registered colour of the accepted plate contradicts what the camera saw, and the make is not on "
                  "record, so the context features could not veto it. Proposed remedy (not applied here): an RDR "
                  "exception under R5 that quarantines a plate correction whose candidate's registered colour "
                  "disagrees with the observed colour, which needs a colour-agreement feature next to the existing "
                  "`match_best_make_agrees`."]
    else:  # Workstream H: the finding the first run produced, and how it was closed, stays on record
        lines += ["", "## Every wrong correction (findings)", "",
                  "None in this run. The first run (same seed) found one: the double misread `UP16ABO524` (truth "
                  "`UP16AB0521`) was corrected by R5 to `UP16AB0524`, an ACCEPT at p=0.948, although that plate is "
                  "registered Grey (make not on record) and the camera saw a Red Hyundai i20. It was closed by "
                  "knowledge acquisition, not by tuning: new context features `match_best_colour_agrees` and "
                  "`match_best_model_agrees` (canonical lexicon forms, None when either side is unknown) and an RDR "
                  "exception under R5, added through `RDRTree.add_exception` by `scripts/add_colour_veto_rule.py` "
                  "with that exact case as its cornerstone: if the accepted candidate's registered colour or model "
                  "disagrees with the observation, quarantine. The case now counts as a quarantine (safe, but not a "
                  "correct correction), so `plate_misread_double` correction accuracy is unchanged and its "
                  "quarantine rate rises by one record (0.20 -> 0.24)."]
    lines += ["", "## Reading the numbers", "",
              "- A plate the matcher does not ACCEPT is **quarantined**, never guessed: for misreads a quarantine is a "
              "safe outcome that counts against correction accuracy but never as a wrong correction.",
              "- `clone_swap` is a valid make and colour of another real vehicle. The right outcome is a FLAG "
              "(clone evidence, rule R4); overwriting it with the registered value would destroy the evidence, "
              "so any `set` there counts as wrong.",
              "- `low_confidence_corroborated` is expected to raise nothing: low OCR confidence on a read whose "
              "make and colour agree with the registration is kept by design (rule R8). Its false-alarm column "
              "measures that.",
              "- Timestamps that cannot be read, or postdate the present, cannot be repaired from context, so the "
              "expected action is quarantine.", ""]
    return "\n".join(lines)


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n", type=int, default=300)
    ap.add_argument("--seed", type=int, default=cv.SEED)
    ap.add_argument("--local-db", action="store_true", help="read this laptop's SQLite copies instead of the wrappers")
    ap.add_argument("--json", default=str(cv.OUT_JSON))
    ap.add_argument("--md", default=str(DOC))
    args = ap.parse_args(argv)
    rep = cv.validate(n=args.n, seed=args.seed, local_db=args.local_db)
    Path(args.json).write_text(json.dumps(rep, indent=2, default=str) + "\n", encoding="utf-8")
    Path(args.md).write_text(markdown(rep), encoding="utf-8")
    o = rep["overall"]
    print(f"recall {o['detection_recall']}  precision {o['detection_precision']}  correction {o['correction_accuracy']}  "
          f"wrong {o['wrong_corrections']}  wrong plates {o['plate_wrong_corrections']}")
    for kind, t in rep["per_type"].items():
        print(f"  {kind:28} n={t['n']:3}  recall {_cell(t['detection_recall']):5}  fa {_cell(t['false_alarm_rate']):5}  "
              f"correct {_cell(t['correction_accuracy']):5}  quar {_cell(t['quarantine_rate']):5}  wrong {t['wrong_corrections']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
