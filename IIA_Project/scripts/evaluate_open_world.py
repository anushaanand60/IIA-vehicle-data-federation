"""Before / after the open-world check (mediator/open_world.py): does the matcher still trust what it should?

PHASE3-ADDED (C3: matching re-evaluated) -- new in phase 3.

The examiner typed `0L01AB1234` and the matcher answered DL01AB1234 at p=1.000. This measures, on the
held-out test vehicles (same split, seed and simulated camera context as scripts/evaluate_matching.py),
the phase-2 matcher ("before", `open_world_check=False`) against the phase-3 one ("after"):

    honest reads        the benchmark's real OCR reads of registered test vehicles: ACCEPT recall and precision
    unknown neighbour   a valid plate one digit away from a registered test plate that no source holds, read
                        exactly: every ACCEPT is wrong (the car is not the registered one)
    state code 0        the examiner's case: the first letter of a test plate read as 0
    unknown state XX    both state letters unreadable
    truncated           the last two digits lost

and the same "after" pipeline for RHO = 0.01, 0.05 (in use) and 0.2. Read-only; writes docs/OPEN_WORLD.md.

    python scripts/evaluate_open_world.py
"""
from __future__ import annotations

import sys
from pathlib import Path
from typing import Callable, Dict, List, Tuple

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "scripts")]

import evaluate_matching as em  # noqa: E402
from mediator import confusion, open_world, plate_match as pm  # noqa: E402

DOC = ROOT / "docs" / "OPEN_WORLD.md"
Case = Tuple[str, float, str, Dict[str, str]]  # read, confidence, true plate (or "" if none held), context


def _unknown_neighbour(plate: str, held: set) -> str:
    for i in range(len(plate) - 1, len(plate) - 5, -1):  # the 4-digit number, last digit first
        for d in "0123456789":
            cand = plate[:i] + d + plate[i + 1:]
            if cand != plate and cand not in held and open_world.is_valid(cand):
                return cand
    return ""


def build_cases() -> Dict[str, List[Case]]:
    rows, reg = em.load_rows(), pm.load_registry()
    lab = [r for r in rows if r["true_plate"] and r["degradation"] != "observed"]
    split = confusion.split_by_plate([r["true_plate"] for r in lab], em.SEED)
    pools = {a: sorted({v[a] for v in reg.values() if v[a]}) for a in ("make", "model", "colour")}
    test = [r for r in lab if split[r["true_plate"]] == "test" and r["true_plate"] in reg and r["ocr_read"]]
    plates = sorted({r["true_plate"] for r in test})
    none = {"make": None, "model": None, "colour": None}
    cases: Dict[str, List[Case]] = {
        "honest reads": [(r["ocr_read"], em._conf(r), r["true_plate"], em.simulate_context(r, reg, pools))
                         for r in test]}
    cases["unknown neighbour"] = [(u, 0.9, "", none) for u in (_unknown_neighbour(p, set(reg)) for p in plates) if u]
    cases["state code 0"] = [("0" + p[1:], 0.9, p, none) for p in plates]
    cases["unknown state XX"] = [("XX" + p[2:], 0.9, p, none) for p in plates]
    cases["truncated"] = [(p[:-2], 0.9, p, none) for p in plates]
    return cases


def score(cases: List[Case], run: Callable[[str, float, Dict[str, str]], List[pm.Candidate]]) -> Dict[str, float]:
    acc = right = top_right = 0
    shown: List[float] = []
    for read, conf, truth, ctx in cases:
        ranked = run(read, conf, ctx)
        if not ranked:
            continue
        t = ranked[0]
        shown.append(t.probability)
        top_right += bool(truth) and t.plate == truth
        if t.decision == "ACCEPT":
            acc += 1
            right += bool(truth) and t.plate == truth
    n = max(1, len(cases))
    return {"accept": acc / n, "recall": right / n, "precision": right / max(1, acc), "top": top_right / n,
            "mean_p": sum(shown) / max(1, len(shown))}


def main() -> None:
    reg = pm.load_registry()
    cases = build_cases()

    def runner(check: bool) -> Callable[[str, float, Dict[str, str]], List[pm.Candidate]]:
        def run(read: str, conf: float, ctx: Dict[str, str]) -> List[pm.Candidate]:
            return pm.match(read, confidence=conf, observed_make=ctx["make"], observed_colour=ctx["colour"],
                            observed_model=ctx["model"], registry=reg, open_world_check=check)[0]
        return run

    lines = ["# Open-world matching: before and after", "",
             "Generated by `python scripts/evaluate_open_world.py`. *Before* is the phase-2 matcher "
             "(logistic regression + Platt, registry-only); *after* adds `mediator/open_world.py` (the probability is "
             "the model's times p(the car is one a source holds), and a correction inside the state code is never auto-accepted). Test vehicles only.",
             "", "| case | n | | auto-ACCEPT | ACCEPT right | ACCEPT precision | top candidate right | mean p shown |",
             "|---|---|---|---|---|---|---|---|"]
    for name, cs in cases.items():
        for label, check in (("before", False), ("after", True)):
            s = score(cs, runner(check))
            lines.append(f"| {name if label == 'before' else ''} | {len(cs) if label == 'before' else ''} | {label} | "
                         f"{s['accept']:.3f} | {s['recall']:.3f} | {s['precision']:.3f} | {s['top']:.3f} | {s['mean_p']:.3f} |")
    lines += ["", "An *unknown neighbour* is a car no source holds, so for it every auto-ACCEPT is a wrong vehicle. "
              "For the other synthetic cases the right answer exists, but the read alone cannot prove it: a person "
              "(or, in the GUI, the other databases and the photo's make and colour) must confirm it.", "",
              "## Sensitivity to RHO (prior weight of a plate no source holds)", "",
              "| RHO | honest ACCEPT right | honest precision | unknown neighbour auto-ACCEPT |", "|---|---|---|---|"]
    keep = open_world.RHO
    try:
        for rho in (0.01, 0.05, 0.2):
            open_world.RHO = rho
            h, u = score(cases["honest reads"], runner(True)), score(cases["unknown neighbour"], runner(True))
            lines.append(f"| {rho}{' (in use)' if rho == keep else ''} | {h['recall']:.3f} | {h['precision']:.3f} | "
                         f"{u['accept']:.3f} |")
    finally:
        open_world.RHO = keep
    DOC.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwrote {DOC.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
