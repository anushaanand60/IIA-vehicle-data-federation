"""Why the matcher's context veto is "two or more contradictions" (plate_match.CONTEXT_VETO).

An exact plate read outweighs the camera's make / model / colour in the logistic regression, so a
cloned plate (the right characters on another vehicle) was ACCEPTed automatically. A veto holds such an
ACCEPT at REVIEW; the question is how many contradicting attributes it should take. On the held-out
test vehicles (same split, seed and simulated camera context as scripts/evaluate_matching.py), each
read is matched twice: with the honest simulated context, and as a clone (the context of a random other
registered vehicle). Each policy is scored on honest ACCEPT recall, ACCEPT precision, and the share of
clones it still accepts without a person. Read-only; writes docs/CONTEXT_VETO.md.

    python scripts/evaluate_context_veto.py
"""
from __future__ import annotations

import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "scripts")]

import evaluate_matching as em  # noqa: E402
from mediator import confusion, plate_match as pm  # noqa: E402

DOC = ROOT / "docs" / "CONTEXT_VETO.md"
POLICIES = {"no veto": 99, "any one contradicts": 1, "two or more contradict (in use)": 2, "all three contradict": 3}


def main() -> None:
    rows, reg = em.load_rows(), pm.load_registry()
    lab = [r for r in rows if r["true_plate"] and r["degradation"] != "observed"]
    split = confusion.split_by_plate([r["true_plate"] for r in lab], em.SEED)
    pools = {a: sorted({v[a] for v in reg.values() if v[a]}) for a in ("make", "model", "colour")}
    test = [r for r in lab if split[r["true_plate"]] == "test" and r["true_plate"] in reg and r["ocr_read"]]
    rng = random.Random(em.SEED)

    def top(r, ctx):
        ranked, _ = pm.match(r["ocr_read"], confidence=em._conf(r), observed_make=ctx["make"],
                             observed_colour=ctx["colour"], observed_model=ctx["model"], registry=reg)
        if not ranked:
            return None, 0
        t = ranked[0]
        would_accept = t.decision == "ACCEPT" or any("would ACCEPT" in x for x in t.reasons)
        return (t if would_accept else None), sum(t.features.get(k) == -1.0 for k in pm.CONTEXT_KEYS)

    honest = [(r, *top(r, em.simulate_context(r, reg, pools))) for r in test]
    clones = []
    for r in test:
        other = reg[rng.choice([p for p in sorted(reg) if p != r["true_plate"]])]
        clones.append((r, *top(r, {"make": other["make"], "model": other["model"], "colour": other["colour"]})))
    lines = ["# Context veto: how many contradictions hold an ACCEPT at REVIEW", "",
             f"Generated by `python scripts/evaluate_context_veto.py` on {len(test)} held-out test reads whose true "
             "plate is registered (seed and simulated camera context as in MATCHING_EVALUATION.md: make right 85 %, "
             "model 70 %, colour 75 %). A clone is the same read seen with a random other vehicle's make, model and colour.",
             "", "| policy | honest ACCEPT recall | ACCEPT precision | clones auto-ACCEPTed |", "|---|---|---|---|"]
    for name, k in POLICIES.items():
        acc = [(r, t) for r, t, n in honest if t is not None and n < k]
        right = sum(t.plate == r["true_plate"] for r, t in acc)
        cl = sum(1 for _, t, n in clones if t is not None and n < k)
        lines.append(f"| {name} | {right / len(honest):.3f} | {right / max(1, len(acc)):.3f} | {cl / len(clones):.3f} |")
        print(lines[-1])
    lines += ["", "One contradiction alone must not veto: a camera misjudges colour often enough that recall would "
              "halve. Two or more independent contradictions mean a different vehicle, so the plate is identified "
              "but the car is not, and a person decides (Data Cleansing's R4 flags the same record as clone evidence)."]
    DOC.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
